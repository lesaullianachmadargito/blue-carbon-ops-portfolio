#!/usr/bin/env python3
"""Mangrove carbon stock from plot data: a worked example with illustrative numbers.

ILLUSTRATIVE DATA. The stems and soil cores below are generated by this script
from a fixed random seed. They are not measurements from any real site, and no
CarbonEthics data were used. The point is the workflow and the checks, not the
numbers.

What the script does
  1. builds an illustrative inventory: 8 circular plots of 7 m radius with stem
     diameters by species, and one soil core per plot cut into 4 depth layers;
  2. turns stems into above- and below-ground biomass with the common mangrove
     equations of Komiyama et al. (2005), then into carbon;
  3. turns soil loss-on-ignition (LOI) into organic carbon with two published
     equations and sums soil carbon to 1 m;
  4. reports per-hectare means with 90 % and 95 % confidence intervals, the
     plot-to-plot coefficient of variation, and the plots needed for a target
     precision;
  5. shows how strongly a "CO2e per tree" figure depends on survival.

Run:   python carbon_stock.py          (writes ./outputs next to this file)
"""

import csv
import json
import math
from pathlib import Path

import numpy as np
from scipy import stats

HERE = Path(__file__).resolve().parent
OUT = HERE / "outputs"

# --------------------------------------------------------------------------
# Parameters. Anything marked PLACEHOLDER must be replaced before real use.
# --------------------------------------------------------------------------
PARAMS = {
    "plot_radius_m": 7.0,
    # IPCC 2006 default carbon fraction for woody biomass, applied to both pools
    # here. Replace with the value the project methodology fixes.
    "carbon_fraction": 0.47,
    "co2_per_c": 44.0 / 12.0,
    # Basic wood density, g/cm3. PLACEHOLDER values: take species values from the
    # Global Wood Density Database (Zanne et al. 2009) or a site study.
    "wood_density": {"Rhizophora mucronata": 0.80, "Avicennia marina": 0.65},
    "small_stem_cm": 5.0,
    "soil_layers_cm": [[0, 15], [15, 30], [30, 50], [50, 100]],
    # %OC = a * %LOI + b
    "loi_to_oc": {
        "conventional": {"a": 0.415, "b": 2.89,
                         "label": "Conventional equation (Palau mangroves)"},
        "localized": {"a": 0.36, "b": 2.40,
                      "label": "Localized equation (Philippine mangroves)"},
    },
    "target_precision": [0.10, 0.15, 0.20],
    "confidence": 0.90,
}
PLACEHOLDERS = [f"wood_density[{k}]" for k in PARAMS["wood_density"]]

# Illustrative stand: a planted Rhizophora mucronata stand with gaps from
# mortality and a few natural Avicennia marina recruits.
SEED = 20261009
EXPECTED_STEMS = [70, 92, 64, 38, 85, 58, 96, 47]   # R. mucronata per plot
SOIL_BD = [0.55, 0.65, 0.75, 0.85]                   # g/cm3 by layer
SOIL_LOI = [14.0, 12.0, 10.0, 8.0]                   # % by layer


def agb_kg(d_cm, rho):
    """Above-ground biomass of one stem, kg (Komiyama et al. 2005)."""
    return 0.251 * rho * d_cm ** 2.46


def bgb_kg(d_cm, rho):
    """Root biomass of one stem, kg (Komiyama et al. 2005)."""
    return 0.199 * rho ** 0.899 * d_cm ** 2.22


def oc_pct(loi, a, b):
    return a * loi + b


def make_illustrative_data():
    rng = np.random.default_rng(SEED)
    stems, cores = [], []
    for p, lam in enumerate(EXPECTED_STEMS, start=1):
        plot = f"P{p:02d}"
        for d in rng.lognormal(math.log(5.8), 0.30, rng.poisson(lam)):
            stems.append({"plot": plot, "species": "Rhizophora mucronata",
                          "d_cm": round(float(np.clip(d, 1.5, 14.0)), 1)})
        for d in rng.lognormal(math.log(10.5), 0.30, rng.poisson(2.0)):
            stems.append({"plot": plot, "species": "Avicennia marina",
                          "d_cm": round(float(np.clip(d, 3.0, 22.0)), 1)})
        for (top, bottom), bd, loi in zip(PARAMS["soil_layers_cm"], SOIL_BD, SOIL_LOI):
            cores.append({"plot": plot, "top_cm": top, "bottom_cm": bottom,
                          "bd_g_cm3": round(bd + rng.normal(0, 0.05), 3),
                          "loi_pct": round(max(2.0, loi + rng.normal(0, 1.5)), 2)})
    return stems, cores


def plot_results(stems, cores):
    area_m2 = math.pi * PARAMS["plot_radius_m"] ** 2
    to_mg_ha = 10000.0 / area_m2 / 1000.0          # kg per plot -> Mg per ha
    cf = PARAMS["carbon_fraction"]
    rows = []
    for plot in sorted({s["plot"] for s in stems} | {c["plot"] for c in cores}):
        agb = bgb = small_c = 0.0
        n = 0
        for s in (s for s in stems if s["plot"] == plot):
            rho = PARAMS["wood_density"][s["species"]]
            a, b = agb_kg(s["d_cm"], rho), bgb_kg(s["d_cm"], rho)
            agb, bgb, n = agb + a, bgb + b, n + 1
            if s["d_cm"] < PARAMS["small_stem_cm"]:
                small_c += (a + b) * cf
        row = {"plot": plot, "stems": n,
               "stems_per_ha": round(n * 10000.0 / area_m2),
               "agc_mg_ha": agb * cf * to_mg_ha,
               "bgc_mg_ha": bgb * cf * to_mg_ha}
        row["tree_c_mg_ha"] = row["agc_mg_ha"] + row["bgc_mg_ha"]
        row["small_stem_share"] = small_c * to_mg_ha / row["tree_c_mg_ha"]
        for key, eq in PARAMS["loi_to_oc"].items():
            total = 0.0
            for c in (c for c in cores if c["plot"] == plot):
                thick = c["bottom_cm"] - c["top_cm"]
                layer = c["bd_g_cm3"] * thick * oc_pct(c["loi_pct"], eq["a"], eq["b"])
                row[f"soc_{key}_{c['top_cm']}_{c['bottom_cm']}"] = layer
                total += layer            # g/cm3 x cm x % = Mg C per ha
            row[f"soc_{key}_mg_ha"] = total
        rows.append(row)
    return rows, area_m2


def describe(values, confidence):
    v = np.asarray(values, dtype=float)
    n = v.size
    mean, sd = float(v.mean()), float(v.std(ddof=1))
    se = sd / math.sqrt(n)
    t_c = float(stats.t.ppf(0.5 + confidence / 2, n - 1))
    t95 = float(stats.t.ppf(0.975, n - 1))
    return {"n": n, "mean": mean, "sd": sd, "cv": sd / mean, "se": se,
            "ci90_half": t_c * se, "ci95_half": t95 * se,
            "precision_at_conf": t_c * se / mean}


def plots_needed(cv, precision, confidence):
    """Smallest n with t(n-1) * cv / sqrt(n) <= precision (simple random sampling)."""
    z = stats.norm.ppf(0.5 + confidence / 2)
    n = max(2, math.ceil((z * cv / precision) ** 2))
    while True:
        t_c = stats.t.ppf(0.5 + confidence / 2, n - 1)
        if t_c * cv / math.sqrt(n) <= precision:
            return n
        n += 1


def per_tree_co2e(d_cm, species="Rhizophora mucronata"):
    rho = PARAMS["wood_density"][species]
    c = (agb_kg(d_cm, rho) + bgb_kg(d_cm, rho)) * PARAMS["carbon_fraction"]
    return c * PARAMS["co2_per_c"]


def write_csv(path, rows):
    keys = list(rows[0].keys())
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        for r in rows:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()})


def main():
    OUT.mkdir(exist_ok=True)
    stems, cores = make_illustrative_data()
    rows, area = plot_results(stems, cores)
    conf = PARAMS["confidence"]

    pools = {
        "agc": describe([r["agc_mg_ha"] for r in rows], conf),
        "bgc": describe([r["bgc_mg_ha"] for r in rows], conf),
        "tree_c": describe([r["tree_c_mg_ha"] for r in rows], conf),
        "soc_conventional": describe([r["soc_conventional_mg_ha"] for r in rows], conf),
        "soc_localized": describe([r["soc_localized_mg_ha"] for r in rows], conf),
    }
    total_conv = pools["tree_c"]["mean"] + pools["soc_conventional"]["mean"]
    layers = []
    for top, bottom in PARAMS["soil_layers_cm"]:
        layers.append({
            "layer": f"{top}-{bottom} cm",
            "conventional": float(np.mean([r[f"soc_conventional_{top}_{bottom}"] for r in rows])),
            "localized": float(np.mean([r[f"soc_localized_{top}_{bottom}"] for r in rows])),
        })
    eq_gap = pools["soc_conventional"]["mean"] - pools["soc_localized"]["mean"]

    need = {}
    for key in ("tree_c", "soc_conventional"):
        need[key] = {f"{int(p * 100)}%": plots_needed(pools[key]["cv"], p, conf)
                     for p in PARAMS["target_precision"]}

    survival = [round(s, 2) for s in np.arange(0.1, 1.0001, 0.05)]
    lever = {f"{d} cm": {"per_surviving_tree_kg": per_tree_co2e(d),
                         "per_seedling_planted_kg": [per_tree_co2e(d) * s for s in survival]}
             for d in (4, 6, 8)}

    summary = {
        "illustrative": True,
        "note": "Generated data. Not a measurement from any real site; no CarbonEthics data used.",
        "seed": SEED,
        "placeholders": PLACEHOLDERS,
        "plot_area_m2": area,
        "plots": len(rows),
        "stems_measured": len(stems),
        "pools_mg_c_ha": pools,
        "total_c_mg_ha_conventional": total_conv,
        "total_co2e_mg_ha_conventional": total_conv * PARAMS["co2_per_c"],
        "soil_share_of_total": pools["soc_conventional"]["mean"] / total_conv,
        "small_stem_share_of_tree_c": float(np.mean([r["small_stem_share"] for r in rows])),
        "soil_layers_mean_mg_c_ha": layers,
        "loi_equation_gap_mg_c_ha": eq_gap,
        "loi_equation_gap_pct": eq_gap / pools["soc_conventional"]["mean"],
        "slope_ratio_for_change": PARAMS["loi_to_oc"]["localized"]["a"] / PARAMS["loi_to_oc"]["conventional"]["a"],
        "plots_needed_at_90pct_conf": need,
        "survival_grid": survival,
        "survival_lever_kg_co2e": lever,
        "params": PARAMS,
    }

    write_csv(OUT / "illustrative_stems.csv", stems)
    write_csv(OUT / "illustrative_soil_cores.csv", cores)
    write_csv(OUT / "plot_results.csv", rows)
    with open(OUT / "summary.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    import sys
    sys.path.insert(0, str(HERE))
    import charts
    charts.draw(summary, OUT)

    t = pools["tree_c"]
    print("ILLUSTRATIVE DATA - generated, not measured. PLACEHOLDER parameters in use:", len(PLACEHOLDERS))
    print(f"plots {len(rows)}, stems {len(stems)}, plot area {area:.1f} m2")
    for k, d in pools.items():
        print(f"  {k:17s} mean {d['mean']:7.1f} Mg C/ha  CV {d['cv']*100:5.1f}%  "
              f"90% CI +/-{d['ci90_half']:6.1f} ({d['precision_at_conf']*100:4.1f}% of mean)")
    print(f"  total (conventional soil eq.) {total_conv:.1f} Mg C/ha = {total_conv*PARAMS['co2_per_c']:.0f} Mg CO2e/ha;"
          f" soil share {summary['soil_share_of_total']*100:.0f}%")
    print(f"  LOI equation choice moves soil C by {eq_gap:.1f} Mg C/ha ({summary['loi_equation_gap_pct']*100:.1f}%);"
          f" all tree carbon = {t['mean']:.1f} Mg C/ha")
    print(f"  plots needed for tree carbon at 90% confidence: {need['tree_c']}")
    for d, v in lever.items():
        print(f"  D = {d}: {v['per_surviving_tree_kg']:.1f} kg CO2e per surviving tree")


if __name__ == "__main__":
    main()
